def calculate_odds_ratios(df):
    """Calculate odds ratios for cardiovascular outcomes"""
    outcomes = ['Heart_Attack', 'Stroke', 'Angina']
    results = []

    for outcome in outcomes:
        # Convert Yes/No to 1/0 for analysis
        df['outcome_binary'] = (df[outcome] == 'Yes').astype(int)

        # Overall Black vs White comparison
        black_white_df = df[df['Ethnicity'].isin(['Black', 'White'])]
        table = pd.crosstab(black_white_df['Ethnicity'],
                           black_white_df['outcome_binary'])

        if table.shape == (2, 2):  # Check if we have a valid 2x2 table
            odds_ratio, p_value = fisher_exact(table)

            results.append({
                'Comparison': 'Black vs White (Overall)',
                'Outcome': outcome,
                'OR': odds_ratio,
                'P_value': p_value,
                'N_Black': len(black_white_df[black_white_df['Ethnicity'] == 'Black']),
                'N_White': len(black_white_df[black_white_df['Ethnicity'] == 'White'])
            })

            # Gender-specific comparisons
            for gender in ['Male', 'Female']:
                gender_df = black_white_df[black_white_df['Gender'] == gender]
                table = pd.crosstab(gender_df['Ethnicity'],
                                  gender_df['outcome_binary'])

                if table.shape == (2, 2):
                    odds_ratio, p_value = fisher_exact(table)

                    results.append({
                        'Comparison': f'Black vs White ({gender})',
                        'Outcome': outcome,
                        'OR': odds_ratio,
                        'P_value': p_value,
                        'N_Black': len(gender_df[gender_df['Ethnicity'] == 'Black']),
                        'N_White': len(gender_df[gender_df['Ethnicity'] == 'White'])
                    })

        # Clean up temporary column
        df.drop('outcome_binary', axis=1, inplace=True)

    return pd.DataFrame(results)

