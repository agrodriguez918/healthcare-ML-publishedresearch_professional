def analyze_health_metrics(data):
    # Group proportions
    props = data.groupby(['Ethnicity', 'Gender']).agg({
        'Uncontrolled_BP': 'mean',
        'Higher_URDACT': 'mean',
        'Log_URDACT': ['mean', 'std', 'count']
    }).round(3)

    # Statistical tests
    # BP comparison across all ethnicities using chi-square
    bp_contingency = pd.crosstab(data['Ethnicity'], data['Uncontrolled_BP'])
    bp_test = stats.chi2_contingency(bp_contingency)

    # URDACT comparison using ANOVA
    ethnicities = ['Black', 'White', 'Mexican American', 'Other Hispanic']
    urdact_groups = [data[data['Ethnicity'] == eth]['Log_URDACT'] for eth in ethnicities]
    urdact_test = stats.f_oneway(*urdact_groups)

    # Post-hoc pairwise comparisons for URDACT
    pairwise_tests = {}
    for i, eth1 in enumerate(ethnicities):
        for eth2 in ethnicities[i+1:]:
            group1 = data[data['Ethnicity'] == eth1]['Log_URDACT']
            group2 = data[data['Ethnicity'] == eth2]['Log_URDACT']
            test_result = stats.ttest_ind(group1, group2)
            pairwise_tests[f'{eth1} vs {eth2}'] = test_result

    # Gender-specific tests
    gender_tests = {}
    for gender in ['Male', 'Female']:
        gender_data = data[data['Gender'] == gender]
        urdact_by_gender = [gender_data[gender_data['Ethnicity'] == eth]['Log_URDACT']
                           for eth in ethnicities]
        gender_tests[gender] = stats.f_oneway(*urdact_by_gender)

    # Visualizations
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))

    # BP Category distribution
    sns.barplot(x='Ethnicity', y='Uncontrolled_BP', hue='Gender', data=data, ax=ax1)
    ax1.set_title('Uncontrolled BP Rates by Ethnicity and Gender')
    ax1.set_ylabel('Proportion')
    ax1.tick_params(axis='x', rotation=45)

    # URDACT distribution
    sns.boxplot(x='Ethnicity', y='Log_URDACT', hue='Gender', data=data, ax=ax2)
    ax2.set_title('Log URDACT Distribution')
    ax2.tick_params(axis='x', rotation=45)

    plt.tight_layout()

    return {
        'proportions': props,
        'bp_test': bp_test,
        'urdact_test': urdact_test,
        'pairwise_tests': pairwise_tests,
        'gender_specific_tests': gender_tests
    }

