def calculate_odds_ratio(data, outcome, group_var, ref_group, comp_group, gender=None):
    """
    Calculate odds ratio and p-value for specific group comparisons
    """
    # Filter by gender if specified
    if gender is not None:
        data = data[data['Gender'] == gender]

    # Create contingency table
    ref_data = data[data[group_var] == ref_group]
    comp_data = data[data[group_var] == comp_group]

    table = pd.DataFrame({
        'Events': [
            (ref_data[outcome] == 'Yes').sum(),
            (comp_data[outcome] == 'Yes').sum()
        ],
        'Non_Events': [
            (ref_data[outcome] == 'No').sum(),
            (comp_data[outcome] == 'No').sum()
        ]
    })

    # Calculate odds ratio and p-value
    odds_ratio, p_value = fisher_exact(table)

    # Calculate confidence intervals
    table_values = table.values.flatten()
    if all(table_values > 0):
        se_log_or = np.sqrt(sum(1/table_values))
        log_or = np.log(odds_ratio)
        ci_lower = np.exp(log_or - 1.96 * se_log_or)
        ci_upper = np.exp(log_or + 1.96 * se_log_or)
    else:
        ci_lower = ci_upper = np.nan

    return {
        'Reference': ref_group,
        'Comparison': comp_group,
        'Gender': gender if gender else 'All',
        'OR': odds_ratio,
        'CI_Lower': ci_lower,
        'CI_Upper': ci_upper,
        'P_Value': p_value,
        'Events_Comp': table.iloc[1,0],
        'Total_Comp': sum(table.iloc[1,:]),
        'Events_Ref': table.iloc[0,0],
        'Total_Ref': sum(table.iloc[0,:])
    }

def run_comprehensive_comparisons(data, outcome):
    """
    Run all possible pairwise comparisons between ethnic and gender groups
    """
    results = []
    ethnic_groups = ['White', 'Black', 'Mexican American', 'Other Hispanic']
    genders = ['Male', 'Female']

    # 1. Overall ethnic comparisons (without gender stratification)
    for ref_group, comp_group in itertools.combinations(ethnic_groups, 2):
        results.append(calculate_odds_ratio(data, outcome, 'Ethnicity', ref_group, comp_group))

    # 2. Within-gender ethnic comparisons
    for gender in genders:
        for ref_group, comp_group in itertools.combinations(ethnic_groups, 2):
            results.append(calculate_odds_ratio(data, outcome, 'Ethnicity',
                                             ref_group, comp_group, gender))

    # 3. Within-ethnicity gender comparisons
    for ethnic_group in ethnic_groups:
        ethnic_data = data[data['Ethnicity'] == ethnic_group]
        results.append(calculate_odds_ratio(ethnic_data, outcome, 'Gender',
                                         'Female', 'Male'))

    # 4. Cross-ethnic-gender comparisons
    ethnic_gender_groups = list(itertools.product(ethnic_groups, genders))
    for (ref_eth, ref_gen), (comp_eth, comp_gen) in itertools.combinations(ethnic_gender_groups, 2):
        ref_data = data[(data['Ethnicity'] == ref_eth) & (data['Gender'] == ref_gen)]
        comp_data = data[(data['Ethnicity'] == comp_eth) & (data['Gender'] == comp_gen)]

        table = pd.DataFrame({
            'Events': [
                (ref_data[outcome] == 'Yes').sum(),
                (comp_data[outcome] == 'Yes').sum()
            ],
            'Non_Events': [
                (ref_data[outcome] == 'No').sum(),
                (comp_data[outcome] == 'No').sum()
            ]
        })

        odds_ratio, p_value = fisher_exact(table)

        results.append({
            'Reference': f"{ref_eth} {ref_gen}",
            'Comparison': f"{comp_eth} {comp_gen}",
            'Gender': 'Cross-Gender',
            'OR': odds_ratio,
            'CI_Lower': np.nan,  # Calculate if needed
            'CI_Upper': np.nan,  # Calculate if needed
            'P_Value': p_value,
            'Events_Comp': table.iloc[1,0],
            'Total_Comp': sum(table.iloc[1,:]),
            'Events_Ref': table.iloc[0,0],
            'Total_Ref': sum(table.iloc[0,:])
        })

    return pd.DataFrame(results)

