def calculate_risk_metrics(data, outcome, group_var):
    """
    Calculate risk metrics including absolute risk, relative risk, and confidence intervals
    """
    results = []
    categories = sorted(data[group_var].unique())
    reference = categories[0]

    for category in categories:
        # Calculate risks
        group_data = data[data[group_var] == category]
        events = (group_data[outcome] == 'Yes').sum()
        total = len(group_data)
        risk = (events/total) * 100 if total > 0 else 0

        # Calculate reference risk for relative risk
        ref_data = data[data[group_var] == reference]
        ref_events = (ref_data[outcome] == 'Yes').sum()
        ref_total = len(ref_data)
        ref_risk = ref_events/ref_total if ref_total > 0 else 0

        # Calculate relative risk
        rr = (risk/100)/(ref_risk) if ref_risk > 0 else np.nan

        # Calculate confidence intervals
        if events > 0:
            # Wilson score interval for risk
            ci = proportion_confint(events, total)
            risk_ci_lower = ci[0] * 100
            risk_ci_upper = ci[1] * 100

            # Log method for relative risk
            if ref_events > 0:
                log_rr = np.log(rr)
                se_log_rr = np.sqrt((1/events - 1/total) + (1/ref_events - 1/ref_total))
                rr_ci_lower = np.exp(log_rr - 1.96 * se_log_rr)
                rr_ci_upper = np.exp(log_rr + 1.96 * se_log_rr)
            else:
                rr_ci_lower = rr_ci_upper = np.nan
        else:
            risk_ci_lower = risk_ci_upper = 0
            rr_ci_lower = rr_ci_upper = np.nan

        # Calculate risk difference
        risk_diff = risk - (ref_risk * 100)

        results.append({
            'Category': category,
            'Events': events,
            'Total': total,
            'Risk': risk,
            'Risk_CI_Lower': risk_ci_lower,
            'Risk_CI_Upper': risk_ci_upper,
            'Risk_Difference': risk_diff,
            'Relative_Risk': rr,
            'RR_CI_Lower': rr_ci_lower,
            'RR_CI_Upper': rr_ci_upper
        })

    return pd.DataFrame(results)

def analyze_interactions(data, outcome, var1, var2):
    """
    Analyze interactions between two variables
    """
    # Create contingency tables
    results = []

    for val1 in data[var1].unique():
        for val2 in data[var2].unique():
            subset = data[(data[var1] == val1) & (data[var2] == val2)]
            events = (subset[outcome] == 'Yes').sum()
            total = len(subset)
            risk = (events/total * 100) if total > 0 else 0

            # Calculate confidence interval
            if total > 0:
                ci = proportion_confint(events, total)
                ci_lower = ci[0] * 100
                ci_upper = ci[1] * 100
            else:
                ci_lower = ci_upper = 0

            results.append({
                var1: val1,
                var2: val2,
                'Events': events,
                'Total': total,
                'Risk': risk,
                'CI_Lower': ci_lower,
                'CI_Upper': ci_upper
            })

    return pd.DataFrame(results)

def proportion_confint(count, nobs, alpha=0.05, method='wilson'):
    """
    Calculate confidence interval for proportion using Wilson score method
    """
    if nobs == 0:
        return (0, 0)

    p_hat = count / nobs
    z = stats.norm.ppf(1 - alpha/2)

    # Wilson score interval
    denominator = 1 + z**2/nobs
    center = (p_hat + z**2/(2*nobs))/denominator
    spread = z * np.sqrt(p_hat*(1-p_hat)/nobs + z**2/(4*nobs**2))/denominator

    ci_lower = max(0, center - spread)
    ci_upper = min(1, center + spread)

    return (ci_lower, ci_upper)

