def plot_risk_comparison(data, outcome):
    """Create bar plot with proper error bars for risk comparison"""
    ethnicities = ['White', 'Black', 'Mexican American', 'Other Hispanic']
    width = 0.35

    # Initialize arrays for storing results
    male_risks = []
    female_risks = []
    male_errors = []
    female_errors = []

    # Calculate risks and confidence intervals
    for ethnicity in ethnicities:
        # Male calculations
        male_data = data[(data['Ethnicity'] == ethnicity) & (data['Gender'] == 'Male')]
        male_total = len(male_data)
        male_events = (male_data[outcome] == 'Yes').sum()

        if male_total > 0:
            male_risk = (male_events / male_total) * 100
            # Standard error calculation
            male_se = np.sqrt((male_risk/100 * (1 - male_risk/100)) / male_total) * 100
        else:
            male_risk = 0
            male_se = 0

        male_risks.append(male_risk)
        male_errors.append(male_se * 1.96)  # 95% CI

        # Female calculations
        female_data = data[(data['Ethnicity'] == ethnicity) & (data['Gender'] == 'Female')]
        female_total = len(female_data)
        female_events = (female_data[outcome] == 'Yes').sum()

        if female_total > 0:
            female_risk = (female_events / female_total) * 100
            # Standard error calculation
            female_se = np.sqrt((female_risk/100 * (1 - female_risk/100)) / female_total) * 100
        else:
            female_risk = 0
            female_se = 0

        female_risks.append(female_risk)
        female_errors.append(female_se * 1.96)  # 95% CI

    # Create figure
    plt.figure(figsize=(12, 6))
    x = np.arange(len(ethnicities))

    # Plot bars with error bars
    plt.bar(x - width/2, male_risks, width, label='Male', color='lightblue',
            yerr=male_errors, capsize=5)
    plt.bar(x + width/2, female_risks, width, label='Female', color='pink',
            yerr=female_errors, capsize=5)

