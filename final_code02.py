def analyze_rare_events(data, outcome, predictors):
    """
    Analyze rare events using exact methods
    """
    results = []

    # Create binary outcome
    y = (data[outcome] == 'Yes').astype(int)
    n_events = y.sum()

    for predictor in predictors:
        # Create contingency table
        table = pd.crosstab(data[predictor], y)

        # Calculate chi-square
        chi2, p_value = stats.chi2_contingency(table)[:2]

        # For 2x2 tables, calculate odds ratio
        if table.shape == (2, 2):
            odds_ratio, fisher_p = fisher_exact(table)

            # Calculate confidence intervals
            table_values = table.values.flatten()
            if all(table_values > 0):  # Only calculate CI if no zero cells
                se_log_or = np.sqrt(sum(1/table_values))
                log_or = np.log(odds_ratio)
                ci_lower = np.exp(log_or - 1.96 * se_log_or)
                ci_upper = np.exp(log_or + 1.96 * se_log_or)
