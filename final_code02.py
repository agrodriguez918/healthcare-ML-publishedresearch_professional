def calculate_odds_ratio(data, outcome, ref_group, comp_group, by_var='Ethnicity', gender=None):
    """Calculate odds ratio and confidence intervals"""
    if gender is not None:
        data = data[data['Gender'] == gender]

    # Create contingency table
    ref_data = data[data[by_var] == ref_group]
    comp_data = data[data[by_var] == comp_group]

    table = pd.DataFrame({
        'Events': [
            (ref_data[outcome] == 'Yes').sum(),
            (comp_data[outcome] == 'Yes').sum()
        ],
        'Non_Events': [
            (ref_data[outcome] == 'No').sum(),
            (comp_data[outcome] == 'No').sum()
        ]
    })

    odds_ratio, p_value = fisher_exact(table)

    # Calculate confidence intervals
    table_values = table.values.flatten()
    if all(table_values > 0):
        se_log_or = np.sqrt(sum(1/table_values))
        log_or = np.log(odds_ratio)
        ci_lower = np.exp(log_or - 1.96 * se_log_or)
        ci_upper = np.exp(log_or + 1.96 * se_log_or)
    else:
        ci_lower = ci_upper = np.nan

    return {
        'Reference': ref_group,
        'Comparison': comp_group,
        'Gender': gender if gender else 'All',
        'OR': odds_ratio,
        'CI_Lower': ci_lower,
        'CI_Upper': ci_upper,
        'P_Value': p_value
    }

