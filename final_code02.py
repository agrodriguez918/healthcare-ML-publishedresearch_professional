def age_standardize(df):
    # Define Census 2000 standard population proportions
    standard_population = {
        '0-24': 0.34,
        '25-34': 0.135,
        '35-44': 0.162,
        '45-54': 0.134,
        '55-64': 0.087,
        '65-74': 0.069,
        '75+': 0.073
    }

    # Create age groups
    def create_age_groups(age):
        if age < 25:
            return '0-24'
        elif age < 35:
            return '25-34'
        elif age < 45:
            return '35-44'
        elif age < 55:
            return '45-54'
        elif age < 65:
            return '55-64'
        elif age < 75:
            return '65-74'
        else:
            return '75+'

    # Add age group column
    df['Age_Group'] = df['Age'].apply(create_age_groups)

    # Calculate age-specific rates for each BP category
    age_specific_rates = pd.crosstab(df['Age_Group'], df['BP_Category'], normalize='index')

    # Calculate age-adjusted rates
    adjusted_rates = {}
    for bp_category in ['Normal', 'High_BP', 'Hypertensive']:
        adjusted_rate = 0
        for age_group in standard_population.keys():
            if age_group in age_specific_rates.index:
                specific_rate = age_specific_rates.loc[age_group, bp_category]
                adjusted_rate += specific_rate * standard_population[age_group]
        adjusted_rates[bp_category] = adjusted_rate

    return adjusted_rates

