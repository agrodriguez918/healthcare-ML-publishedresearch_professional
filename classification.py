# Enhanced Simple Ensemble with weighted voting
class WeightedEnsemble:
    def __init__(self, models, weights=None):
        self.models = models
        self.weights = weights if weights is not None else np.ones(len(models))
        self.weights = self.weights / np.sum(self.weights)

    def fit(self, X, y):
        # Train each model and get OOB score to adjust weights
        scores = []
        for model in self.models:
            model.fit(X, y)
            y_pred = model.predict(X)
            score = f1_score(y, y_pred)
            scores.append(score)

        # Update weights based on performance
        self.weights = np.array(scores)
        self.weights = self.weights / np.sum(self.weights)
        return self

    def predict(self, X):
        predictions = np.array([model.predict(X) for model in self.models])
        weighted_sum = np.average(predictions, axis=0, weights=self.weights)
        return (weighted_sum > 0.5).astype(int)

    def predict_proba(self, X):
        probas = np.array([model.predict_proba(X) for model in self.models])
        return np.average(probas, axis=0, weights=self.weights)

# Enhanced Stacking Ensemble with multiple meta-learners
class MultiMetaStacking(BaseEstimator, ClassifierMixin):
    def __init__(self, base_models, meta_learners, n_splits=5):
        self.base_models = base_models
        self.meta_learners = meta_learners
        self.n_splits = n_splits

    def get_params(self, deep=True):
        return {
            "base_models": self.base_models,
            "meta_learners": self.meta_learners,
            "n_splits": self.n_splits
        }

    def _get_meta_features(self, X, y=None, is_train=True):
        if is_train:
            kf = KFold(n_splits=self.n_splits, shuffle=True, random_state=42)
            meta_features = np.zeros((X.shape[0], len(self.base_models)))

            for i, model in enumerate(self.base_models):
                oof_preds = np.zeros(X.shape[0])
                for train_idx, val_idx in kf.split(X):
                    X_train_fold = X[train_idx]
                    X_val_fold = X[val_idx]
                    y_train_fold = y[train_idx]

                    model_clone = clone(model)
                    model_clone.fit(X_train_fold, y_train_fold)
                    oof_preds[val_idx] = model_clone.predict_proba(X_val_fold)[:, 1]

                meta_features[:, i] = oof_preds
                # Fit on full data
                model.fit(X, y)
        else:
            meta_features = np.column_stack([
                model.predict_proba(X)[:, 1] for model in self.base_models
            ])

        return meta_features

    def fit(self, X, y):
        X = np.array(X)
        y = np.array(y)

        # Generate meta-features
        meta_features = self._get_meta_features(X, y, is_train=True)

        # Train meta learners
        for meta_learner in self.meta_learners:
            meta_learner.fit(meta_features, y)

        return self

    def predict(self, X):
        X = np.array(X)
        meta_features = self._get_meta_features(X, is_train=False)

        # Average predictions from all meta learners
        predictions = np.mean([
            meta_learner.predict(meta_features)
            for meta_learner in self.meta_learners
        ], axis=0)

        return (predictions > 0.5).astype(int)

    def predict_proba(self, X):
        X = np.array(X)
        meta_features = self._get_meta_features(X, is_train=False)

        # Average probability predictions from all meta learners
        probas = np.mean([
            meta_learner.predict_proba(meta_features)
            for meta_learner in self.meta_learners
        ], axis=0)

        return probas

