import pandas as pd
import numpy as np
from scipy.stats import fisher_exact
import matplotlib.pyplot as plt

def calculate_odds_ratios(data, outcome, group1, reference_group):
    """
    Calculate odds ratio and Fisher's exact test p-value for 2x2 table.

    Parameters:
    data: DataFrame containing the data
    outcome: Name of the outcome variable
    group1: Name of the grouping variable
    reference_group: Reference group value
    """
    # Create contingency table
    table = pd.crosstab(data[group1], data[outcome])

    # For groups with reference group, calculate odds ratio
    if reference_group in table.index:
        # Ensure reference group is first
        table = table.reindex([reference_group] + [i for i in table.index if i != reference_group])
        odds_ratio, p_value = fisher_exact(table)
        return odds_ratio, p_value, table
    else:
        return None, None, table

