def compute_learning_curve(estimator, X, y, train_sizes):
    """Custom function to compute learning curves"""
    n_samples = len(X)
    scores_train = []
    scores_test = []

    for train_size in train_sizes:
        # Calculate number of samples for this training size
        n_train = int(train_size * n_samples)

        # Create stratified split
        indices = np.random.permutation(n_samples)
        X_train = X.iloc[indices[:n_train]]
        y_train = y.iloc[indices[:n_train]]
        X_test = X.iloc[indices[n_train:]]
        y_test = y.iloc[indices[n_train:]]

        # Train model
        estimator.fit(X_train, y_train)

        # Get scores
        train_score = roc_auc_score(y_train, estimator.predict_proba(X_train)[:, 1])
        test_score = roc_auc_score(y_test, estimator.predict_proba(X_test)[:, 1])

        scores_train.append(train_score)
        scores_test.append(test_score)

    return np.array(scores_train), np.array(scores_test)

