standard_population = {
    '0-24': 0.34,
    '25-34': 0.135,
    '35-44': 0.162,
    '45-54': 0.134,
    '55-64': 0.087,
    '65-74': 0.069,
    '75+': 0.073
}

def create_adjusted_risk_analysis(subset):
    # Create standardized age groups
    def get_std_age_group(age):
        if age < 25: return '0-24'
        elif age < 35: return '25-34'
        elif age < 45: return '35-44'
        elif age < 55: return '45-54'
        elif age < 65: return '55-64'
        elif age < 75: return '65-74'
        else: return '75+'

    subset['Std_Age_Group'] = subset['Age'].apply(get_std_age_group)

    # Calculate age-specific rates by BP category and Ever_High_BP
    age_specific_rates = pd.crosstab(
        [subset['Std_Age_Group'], subset['Ever_High_BP']],
        subset['BP_Category'],
        normalize='index'
    )

    # Calculate age-adjusted rates
    adjusted_rates = {}
    for status in ['Yes', 'No']:  # Ever_High_BP status
        rates = {category: 0 for category in ['Normal', 'High_BP', 'Hypertensive']}
        for age_group in standard_population:
            weight = standard_population[age_group]
            if (age_group, status) in age_specific_rates.index:
                for category in rates:
                    rates[category] += weight * age_specific_rates.loc[(age_group, status), category]
        adjusted_rates[status] = rates

    return pd.DataFrame(adjusted_rates).round(3) * 100

# Run the age-adjusted analysis
adjusted_analysis = create_adjusted_risk_analysis(subset)
print("\nAge-Adjusted BP Category Rates by History of High BP (%):")
print(adjusted_analysis)

# Compare with unadjusted rates
unadjusted = pd.crosstab(subset['Ever_High_BP'],
                         subset['BP_Category'],
                         normalize='index') * 100
print("\nUnadjusted BP Category Rates by History of High BP (%):")
print(unadjusted)



















